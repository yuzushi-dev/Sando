test('standalone bundles match canonical routing metadata and behavior', async () => {
  const modules = await Promise.all([SOURCE, ...BUNDLES].map((directory) => import(pathToFileURL(path.join(directory, 'core.mjs')))));
  const input = {
    toolName: 'Read', output: `${'const value = 1;\n'.repeat(180)}`, cwd: '/work',
    lineCount: 180, fileBytes: 180 * 17,
  };
  const expected = modules[0].optimizeToolOutput(input);

  for (const module of modules.slice(1)) assert.deepEqual(module.optimizeToolOutput(input), expected);
});

// Hand-maintained, not generated by sync-bundles.mjs: these modules have no canonical copy in
// packages/sando/src (they import bundle-only modules such as coverage.mjs), so nothing keeps the
// two copies in step except this gate. A fix landing in one bundle only is exactly how `sando read`
// shipped two different source-class behaviors.
const HAND_MAINTAINED_MODULES = ['artifacts.mjs', 'codex-capabilities.mjs', 'coverage.mjs', 'enforcement.mjs', 'mcp-tools.mjs'];
const HAND_MAINTAINED_BUNDLES = ['adapters/codex/sando/lib', 'plugins/sando/lib'].map((directory) => path.join(ROOT, directory));

test('hand-maintained bundle modules stay identical across bundles', async () => {
  for (const file of HAND_MAINTAINED_MODULES) {
    const [expected, ...rest] = await Promise.all(HAND_MAINTAINED_BUNDLES.map((directory) => fs.readFile(path.join(directory, file), 'utf8')));
    for (const [index, actual] of rest.entries()) {
      assert.equal(actual, expected, `${HAND_MAINTAINED_BUNDLES[index + 1]}/${file} drifted from ${HAND_MAINTAINED_BUNDLES[0]}/${file}`);
    }
  }
});

test('all generated bundle modules match canonical sources', async () => {
  for (const file of GENERATED_MODULES) {
    const expected = await fs.readFile(path.join(SOURCE, file), 'utf8');
    for (const directory of BUNDLES) assert.equal(await fs.readFile(path.join(directory, file), 'utf8'), expected);
  }
});

test('all installed hook bundles emit the contracted hook telemetry shape', () => {
  for (const [directory, host] of [['adapters/claude/sando', 'claude'], ['adapters/codex/sando', 'codex'], ['plugins/sando', 'codex']]) {
    const root = fsSync.mkdtempSync(path.join(os.tmpdir(), 'sando-bundle-hook-'));
    const configPath = path.join(root, 'config', 'sando', 'telemetry.json');
    const statePath = path.join(root, 'state', 'sando', 'telemetry-counters.json');
    fsSync.mkdirSync(path.dirname(configPath), { recursive: true });
    fsSync.writeFileSync(configPath, JSON.stringify({
      schema_version: 1, enabled: true, prompted_consent_version: 1, consent_version: 1,
      consented_at: '2026-08-25T00:00:00.000Z', endpoint: 'http://127.0.0.1:1/v1/logs',
    }));
    execFileSync(process.execPath, [path.join(ROOT, directory, 'hooks/post-tool-use.mjs')], {
      input: JSON.stringify({ hook_event_name: 'PostToolUse', tool_name: 'Bash', tool_response: 'plain output', cwd: root }),
      env: { ...process.env, XDG_CONFIG_HOME: path.join(root, 'config'), XDG_STATE_HOME: path.join(root, 'state'), SANDO_MODE: 'observe' },
    });
    const state = JSON.parse(fsSync.readFileSync(statePath, 'utf8'));
    const summary = Object.values(state.counters).find((row) => row.event === 'hook_summary');
    assert.equal(summary.host, host);
    assert.equal(summary.mode, 'observe');
  }
});

test('canonical and Codex hook bundles preserve the newly written artifact', (t) => {
  const output = 'x'.repeat(60 * 1024);
  const policy = JSON.stringify({ mode: 'apply', maxInlineBytes: 128, maxArtifactBytes: 100_000, redact: false });
  const entrypoints = [
    ['canonical', path.join(ROOT, 'packages/sando/src/hook-cli.mjs'), 'codex'],
    ['codex adapter', path.join(ROOT, 'adapters/codex/sando/lib/hook-entry.mjs'), 'codex'],
    ['Codex plugin', path.join(ROOT, 'plugins/sando/lib/hook-entry.mjs'), 'claude'],
  ];

  for (const [label, entrypoint, host] of entrypoints) {
    const cwd = fsSync.mkdtempSync(path.join(os.tmpdir(), 'sando-hook-artifact-'));
    t.after(() => fsSync.rmSync(cwd, { recursive: true, force: true }));
    const directory = path.join(cwd, '.sando', 'sando', 'artifacts');
    fsSync.mkdirSync(directory, { recursive: true });
    const oldName = `${'f'.repeat(64)}.txt`;
    const oldPath = path.join(directory, oldName);
    fsSync.writeFileSync(oldPath, 'occupied');
    fsSync.truncateSync(oldPath, 64 * 1024 * 1024);
    const future = new Date(Date.now() + 60_000);
    fsSync.utimesSync(oldPath, future, future);

    const runner = path.join(cwd, 'runner.mjs');
    const runnerSource = `import { runHookCli } from ${JSON.stringify(pathToFileURL(entrypoint).href)};\nrunHookCli({ host: ${JSON.stringify(host)} });\n`;
    fsSync.writeFileSync(runner, runnerSource);
    const input = JSON.stringify({ hook_event_name: 'PostToolUse', tool_name: 'Bash', tool_response: output, cwd });
    const result = execFileSync(process.execPath, [runner], {
      input,
      encoding: 'utf8',
      env: {
        ...process.env, DO_NOT_TRACK: '1',
        SANDO_POLICY: policy,
        SANDO_CODEX_FALLBACK: 'feedback',
        SANDO_METRICS_PATH: path.join(cwd, 'metrics.json'),
        XDG_CONFIG_HOME: path.join(cwd, 'config'),
        XDG_STATE_HOME: path.join(cwd, 'state'),
      },
    });

    const emitted = JSON.parse(result);
    if (host === 'codex') assert.equal(emitted.continue, false, label);
    else assert.equal(emitted.hookSpecificOutput.hookEventName, 'PostToolUse', label);
    assert.equal(fsSync.existsSync(oldPath), false, label);
    const artifacts = fsSync.readdirSync(directory).filter((name) => /^[a-f0-9]{64}\.txt$/.test(name));
    assert.equal(artifacts.length, 1, label);
    assert.equal(fsSync.readFileSync(path.join(directory, artifacts[0]), 'utf8'), output, label);
  }
});
